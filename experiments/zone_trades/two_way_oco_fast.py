"""Two-way center straddle with a post-TP OCO, scanned on 15m bars.

Opens are dual market (taker) at the synthetic box midpoint. Original TPs sit
at ± W/2. After the first original TP the remaining leg posts:

  * a reduce-only LIMIT (maker unless the 15m open gaps through) at
    entry * (1 ± (W/2)*alpha) — on the far side of the tape, so it waits
  * an emergency stop-market 1% past the synthetic box extreme (taker)

Same-bar original TPs while both still open count as two-way (maker+maker).
Same later 15m bar tagging both mitigated and emergency → emergency.
Timeout MTM-flattens whatever is still open at the horizon close (taker).
"""

from __future__ import annotations

import json
import logging
from typing import Any

import numpy as np

from experiments.zone_trades.common import forward_window, symbol_bars
from experiments.zone_trades.two_way_width_sweep import (
    HORIZON_BARS,
    HORIZON_NAMES,
    MAX_BARS,
    load_alerts,
)
from hawk_research.data.paths import FEATURES_DIR, REPORTS_DIR

log = logging.getLogger(__name__)

TAKER = 0.0006
MAKER = 0.0002
EMERGENCY = 0.01
WIDTHS_PCT = np.array([0.5, 0.75, 1.0, 1.25, 1.5, 2.0, 2.5, 3.0, 4.0, 5.0], dtype=np.float64)
ALPHAS = np.array([0.25, 0.50, 0.75], dtype=np.float64)
UNVIABLE_MSG = (
    "Strategy unviable: The emergency stops hit during one-way trends erase "
    "all profits generated by the mitigated conditional targets."
)


def first_touch(
    h: np.ndarray,
    low: np.ndarray,
    entry: float,
    half: np.ndarray,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """First 15m bar that tags an original TP; which side(s) printed."""
    tp_l = entry * (1.0 + half)
    tp_s = entry * (1.0 - half)
    hit_l = h[:, None] >= tp_l[None, :]
    hit_s = low[:, None] <= tp_s[None, :]
    hit = hit_l | hit_s
    any_hit = hit.any(axis=0)
    first_i = np.argmax(hit, axis=0).astype(np.int32)
    first_i = np.where(any_hit, first_i, np.int32(-1))
    idx = np.clip(first_i, 0, None)
    cols = np.arange(len(half))
    both = any_hit & hit_l[idx, cols] & hit_s[idx, cols]
    long_hit = any_hit & hit_l[idx, cols]
    short_hit = any_hit & hit_s[idx, cols]
    return first_i, both, long_hit, short_hit


def oco_scan(
    rest_h: np.ndarray,
    rest_l: np.ndarray,
    rest_o: np.ndarray,
    entry: float,
    x: float,
    long_won: bool,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """After the TP bar: first mitigated vs emergency per alpha.

    Returns outcome (1=mit, 2=emg, 3=none), remaining-leg pnl, extra fee.
    Same bar tagging both → emergency.
    """
    n_a = len(ALPHAS)
    oc = np.full(n_a, 3, dtype=np.int8)
    rem = np.zeros(n_a, dtype=np.float64)
    extra = np.zeros(n_a, dtype=np.float64)
    n = int(rest_h.size)
    if n == 0:
        return oc, rem, extra
    if long_won:
        mit = entry * (1.0 + x * ALPHAS)
        emg = entry * (1.0 + x) * (1.0 + EMERGENCY)
        hit_m = rest_l[:, None] <= mit[None, :]
        he = rest_h >= emg
    else:
        mit = entry * (1.0 - x * ALPHAS)
        emg = entry * (1.0 - x) * (1.0 - EMERGENCY)
        hit_m = rest_h[:, None] >= mit[None, :]
        he = rest_l <= emg
    hit = hit_m | he[:, None]
    any_hit = hit.any(axis=0)
    if not bool(any_hit.any()):
        return oc, rem, extra
    fj = np.argmax(hit, axis=0)
    for ai in range(n_a):
        if not bool(any_hit[ai]):
            continue
        j = int(fj[ai])
        op = float(rest_o[j])
        if bool(he[j]):
            oc[ai] = 2
            extra[ai] = TAKER
            if long_won:
                fill = op if op >= emg else emg
                rem[ai] = (entry - fill) / entry
            else:
                fill = op if op <= emg else emg
                rem[ai] = (fill - entry) / entry
            continue
        oc[ai] = 1
        m = float(mit[ai])
        if long_won:
            if op < m:
                fill = op
                extra[ai] = TAKER
            else:
                fill = m
                extra[ai] = MAKER
            rem[ai] = (entry - fill) / entry
        else:
            if op > m:
                fill = op
                extra[ai] = TAKER
            else:
                fill = m
                extra[ai] = MAKER
            rem[ai] = (fill - entry) / entry
    return oc, rem, extra


def summarize(
    nets: np.ndarray,
    outcomes: np.ndarray,
    width_pct: float,
    alpha: float,
    horizon: str,
) -> dict[str, Any]:
    n = int(len(nets))
    gp = float(nets[nets > 0].sum()) if n else 0.0
    gl = float(-nets[nets < 0].sum()) if n else 0.0

    def mean_where(mask: np.ndarray) -> float | None:
        return float(nets[mask].mean() * 100.0) if mask.any() else None

    return {
        "horizon": horizon,
        "width_pct": float(width_pct),
        "alpha_pct": float(alpha * 100.0),
        "n": n,
        "two_way_pct": float((outcomes == 0).mean() * 100.0) if n else 0.0,
        "mitigated_pct": float((outcomes == 1).mean() * 100.0) if n else 0.0,
        "emergency_pct": float((outcomes == 2).mean() * 100.0) if n else 0.0,
        "timeout_pct": float((outcomes == 3).mean() * 100.0) if n else 0.0,
        "net_avg_pct": float(nets.mean() * 100.0) if n else 0.0,
        "two_way_mean_pct": mean_where(outcomes == 0),
        "mitigated_mean_pct": mean_where(outcomes == 1),
        "emergency_mean_pct": mean_where(outcomes == 2),
        "timeout_mean_pct": mean_where(outcomes == 3),
        "profit_factor": (gp / gl) if gl > 0 else None,
        "profitable_net": bool(n and nets.mean() > 0),
    }


def sweep() -> dict[str, Any]:
    alerts = load_alerts(FEATURES_DIR / "zone_dataset.parquet")
    log.info(f"alerts={len(alerts)}")

    half = (WIDTHS_PCT / 100.0) / 2.0
    n_w = len(WIDTHS_PCT)
    n_a = len(ALPHAS)
    n_h = len(HORIZON_BARS)

    nets: list[list[list[list[float]]]] = [[[[] for _ in range(n_a)] for _ in range(n_w)] for _ in range(n_h)]
    outs: list[list[list[list[int]]]] = [[[[] for _ in range(n_a)] for _ in range(n_w)] for _ in range(n_h)]
    n_used = 0

    for sym, g in alerts.groupby("symbol", sort=False):
        bars = symbol_bars(sym)
        if bars is None:
            continue
        log.info(f"{sym} n={len(g)}")
        for entry, src_t in zip(
            g["mid"].to_numpy(dtype=np.float64), g["source_open_time"].to_numpy(dtype=np.int64)
        ):
            entry = float(entry)
            w = forward_window(bars["open_time"], src_t, MAX_BARS, min_bars=HORIZON_BARS[0])
            if w is None:
                continue
            oo, hh, ll, cc = bars["open"][w], bars["high"][w], bars["low"][w], bars["close"][w]
            ncont = len(hh)
            first_i, both, long_hit, short_hit = first_touch(hh, ll, entry, half)
            n_used += 1

            for hi, need in enumerate(HORIZON_BARS):
                if ncont < need:
                    continue
                close_px = float(cc[need - 1])
                for wi in range(n_w):
                    x = float(half[wi])
                    w = float(WIDTHS_PCT[wi] / 100.0)
                    fi = int(first_i[wi])
                    tp_in = fi >= 0 and fi < need
                    if not tp_in:
                        net = -4.0 * TAKER
                        for ai in range(n_a):
                            nets[hi][wi][ai].append(net)
                            outs[hi][wi][ai].append(3)
                        continue
                    if bool(both[wi]):
                        net = w - 2.0 * TAKER - 2.0 * MAKER
                        for ai in range(n_a):
                            nets[hi][wi][ai].append(net)
                            outs[hi][wi][ai].append(0)
                        continue

                    long_won = bool(long_hit[wi])
                    tp = entry * (1.0 + x) if long_won else entry * (1.0 - x)
                    op0 = float(oo[fi])
                    if long_won:
                        tp_fee = TAKER if op0 > tp else MAKER
                    else:
                        tp_fee = TAKER if op0 < tp else MAKER
                    locked = x
                    oc_a, rem_a, extra_a = oco_scan(
                        hh[fi + 1 : need],
                        ll[fi + 1 : need],
                        oo[fi + 1 : need],
                        entry,
                        x,
                        long_won,
                    )
                    if long_won:
                        mtm = (entry - close_px) / entry
                    else:
                        mtm = (close_px - entry) / entry
                    for ai in range(n_a):
                        oc = int(oc_a[ai])
                        if oc == 3:
                            net = locked + mtm - (2.0 * TAKER + tp_fee + TAKER)
                        else:
                            net = locked + float(rem_a[ai]) - (2.0 * TAKER + tp_fee + float(extra_a[ai]))
                        nets[hi][wi][ai].append(net)
                        outs[hi][wi][ai].append(oc)

    rows: list[dict[str, Any]] = []
    for hi, name in enumerate(HORIZON_NAMES):
        for wi, width_pct in enumerate(WIDTHS_PCT):
            for ai, alpha in enumerate(ALPHAS):
                if not nets[hi][wi][ai]:
                    continue
                row = summarize(
                    np.asarray(nets[hi][wi][ai], dtype=np.float64),
                    np.asarray(outs[hi][wi][ai], dtype=np.int8),
                    float(width_pct),
                    float(alpha),
                    name,
                )
                rows.append(row)
                log.info(
                    f"  {name} w={row['width_pct']:5.2f}% a={row['alpha_pct']:2.0f}%  "
                    f"mit={row['mitigated_pct']:5.1f}%  emg={row['emergency_pct']:5.1f}%  "
                    f"2way={row['two_way_pct']:4.1f}%  to={row['timeout_pct']:5.1f}%  "
                    f"net={row['net_avg_pct']:+.4f}%  "
                    f"{'PROFIT' if row['profitable_net'] else 'loss'}"
                )

    profitable = [r for r in rows if r["profitable_net"]]
    best = max(rows, key=lambda r: r["net_avg_pct"]) if rows else None
    unviable = not bool(profitable)
    report = {
        "entry": "box midpoint; dual long+short, taker",
        "bars": "15m first-touch original TPs, then 15m scan after that bar for OCO",
        "oco": {
            "mitigated_limit": "entry * (1 ± (W/2)*alpha), maker unless 15m open gaps through",
            "emergency_stop": "1% past synthetic box extreme, taker",
            "resolution": "same 15m bar tags limit and emergency -> emergency",
        },
        "fees": "taker 0.06% market / maker 0.02% passive limits; two taker opens always",
        "n_alerts": int(len(alerts)),
        "n_used": int(n_used),
        "rows": rows,
        "any_profitable": bool(profitable),
        "profitable_rows": profitable,
        "best": best,
        "unviable": unviable,
        "unviable_message": UNVIABLE_MSG if unviable else None,
    }
    out = REPORTS_DIR / "two_way_oco.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2), encoding="utf-8")
    log.info(f"wrote {out} n_used={n_used} any_profit={bool(profitable)}")
    if unviable:
        log.info(UNVIABLE_MSG)
    return report


if __name__ == "__main__":
    sweep()
